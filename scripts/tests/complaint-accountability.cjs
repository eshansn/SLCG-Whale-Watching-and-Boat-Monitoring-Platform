// Invoked by ComplaintAccountabilityTests against a disposable SQL database and live API.
// API and SignalR traffic is never mocked or intercepted.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
const base = process.env.WWMS_WEB_URL;
const complaintId = process.env.WWMS_COMPLAINT_ID;
const passengerId = process.env.WWMS_PASSENGER_ID;

async function main() {
  assert(base && complaintId && passengerId, 'Run through the isolated SQL test harness.');
  const browser = await chromium.launch({ headless: true, channel: process.env.PLAYWRIGHT_CHANNEL || 'msedge' });
  const contexts = [];
  const errors = [];
  const screenshots = process.env.WWMS_BROWSER_SCREENSHOTS;
  if (screenshots) fs.mkdirSync(screenshots, { recursive: true });
  const session = async (role) => {
    const context = await browser.newContext(); contexts.push(context);
    const response = await context.request.post(`${base}api/auth/login`, {
      data: { email: `${role.toLowerCase()}@complaint-test.example`, password: 'BrowserTest#2026!Only' },
    });
    assert.equal(response.status(), 200, `Live login for ${role}`);
    const auth = await response.json();
    await context.addInitScript(token => {
      if (!sessionStorage.getItem('whale-watching-refresh-token')) sessionStorage.setItem('whale-watching-refresh-token', token);
    }, auth.refreshToken);
    const page = await context.newPage();
    page.on('pageerror', error => errors.push(error.message));
    return page;
  };
  const actionComplete = page => page.getByRole('status').filter({ hasText: 'Complaint action recorded.' }).waitFor();
  const assertNoOverflow = async page => assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), 'Mobile page must fit the viewport');
  const assertSingleHeader = async page => {
    assert.equal(await page.locator('header').count(), 1, 'Only the existing portal header should be rendered');
    assert.equal(await page.getByRole('navigation', { name: 'Complaint coordination' }).count(), 0, 'No secondary complaint navigation bar');
  };
  try {
    const sltda = await session('SLTDA');
    const inquirySubmission = await sltda.context().request.post(`${base}api/complaints`, {
      headers: { 'X-Passenger-Session': 'test-passenger-session' },
      multipart: { Type: 'Other', Kind: 'Inquiry', Message: 'Browser classification inquiry', RequestId: require('node:crypto').randomUUID() },
    });
    assert.equal(inquirySubmission.status(), 201);
    const inquiryId = (await inquirySubmission.json()).id;
    await sltda.goto(`${base}sltda`);
    await sltda.getByRole('heading', { name: 'Passenger activity', exact: true }).waitFor();
    await sltda.getByRole('link', { name: /^Total passengers: 3/ }).waitFor();
    assert(!/accountability/i.test(await sltda.locator('h1').innerText()));
    await assertSingleHeader(sltda);
    assert.equal(await sltda.locator('header').getByRole('link', { name: 'Complaints & inquiries', exact: true }).count(), 1);
    await sltda.emulateMedia({ reducedMotion: 'reduce' });
    await sltda.getByRole('figure', { name: 'Passenger registration trend', exact: true }).locator('svg.recharts-surface').waitFor();
    await sltda.getByRole('figure', { name: 'Complaint and inquiry submission trend', exact: true }).locator('svg.recharts-surface').waitFor();
    await sltda.getByRole('button', { name: '7 days', exact: true }).click();
    await sltda.waitForURL(url => url.searchParams.has('from'));
    await sltda.getByLabel('Chart interval').selectOption('weekly');
    await sltda.waitForURL(url => url.searchParams.get('interval') === 'weekly');
    await sltda.getByText('New passenger profiles · weekly totals', { exact: true }).waitFor();
    await sltda.getByRole('button', { name: '30 days', exact: true }).click();
    await sltda.getByRole('link', { name: /^Inquiries 1$/ }).waitFor();
    await sltda.getByText('View registration data', { exact: true }).click();
    const registrationRows = sltda.locator('details').filter({ hasText: 'View registration data' }).locator('tbody tr');
    await registrationRows.first().waitFor();
    assert.equal(await registrationRows.count(), 30);
    await sltda.getByText('View registration data', { exact: true }).click();
    const download = sltda.waitForEvent('download');
    await sltda.getByRole('button', { name: 'Export summary', exact: true }).click();
    assert.match((await download).suggestedFilename(), /^SLTDA-activity-.*\.csv$/);
    if (screenshots) await sltda.screenshot({ path: path.join(screenshots, 'sltda-dashboard.png'), fullPage: true });
    await sltda.getByRole('link', { name: /^Inquiries 1$/ }).click();
    await sltda.waitForURL(url => url.pathname === '/sltda/complaints' && url.searchParams.get('kind') === 'Inquiry');
    await sltda.locator('article').getByRole('link', { name: new RegExp(`^WWMS-${inquiryId}$`, 'i') }).waitFor();
    assert.equal(await sltda.getByLabel('Record kind', { exact: true }).inputValue(), 'Inquiry');
    assert.equal(await sltda.locator('article').count(), 1);
    await sltda.reload();
    await sltda.locator('article').getByRole('link', { name: new RegExp(`^WWMS-${inquiryId}$`, 'i') }).waitFor();
    assert.equal(await sltda.getByLabel('Record kind', { exact: true }).inputValue(), 'Inquiry');
    await sltda.locator('header').getByRole('link', { name: 'Dashboard', exact: true }).click();
    await sltda.getByRole('link', { name: /^Open cases: 2/ }).click();
    await sltda.getByLabel('Case queue', { exact: true }).waitFor();
    assert.equal(await sltda.getByLabel('Case queue', { exact: true }).inputValue(), 'open');
    await sltda.locator('header').getByRole('link', { name: 'Dashboard', exact: true }).click();
    await sltda.getByRole('link', { name: /^Registered trips:/ }).click();
    await sltda.getByRole('heading', { name: 'Trip history', exact: true }).waitFor();
    assert(new URL(sltda.url()).searchParams.has('from'));
    await sltda.getByRole('link', { name: 'Test boat', exact: true }).click();
    await sltda.getByRole('heading', { name: 'Test boat', exact: true }).waitFor();
    await sltda.locator('header').getByRole('link', { name: 'Trip history', exact: true }).click();
    await sltda.getByRole('heading', { name: 'Trip history', exact: true }).waitFor();
    await sltda.getByRole('table').getByText('Completed', { exact: true }).waitFor();
    await sltda.locator('header').getByRole('link', { name: 'Dashboard', exact: true }).click();
    await sltda.getByRole('link', { name: /^New registrations:/ }).click();
    await sltda.waitForURL(url => url.pathname === '/sltda/passengers');
    await sltda.locator('h1').filter({ hasText: 'Passenger monitoring' }).waitFor();
    assert(new URL(sltda.url()).searchParams.has('from'));
    await sltda.getByRole('link', { name: 'Passenger One', exact: true }).click();
    await sltda.getByRole('heading', { name: 'Trip & registration history' }).waitFor();
    await sltda.getByText('Completed', { exact: true }).waitFor();
    await sltda.getByRole('link', { name: new RegExp(`^WWMS-${complaintId}$`, 'i') }).click();
    await sltda.getByRole('heading', { name: 'Safety concern', exact: true }).waitFor();
    await sltda.getByRole('checkbox', { name: 'SLCG', exact: true }).waitFor();
    assert.equal(await sltda.getByRole('checkbox').count(), 4, 'SLCG is one receiving authority');
    for (const role of ['SLTDA', 'HarbourOfficer']) await sltda.getByRole('checkbox', { name: role, exact: true }).waitFor();
    assert.equal(await sltda.getByRole('checkbox', { name: /Admin|OPS|active users/ }).count(), 0);
    await sltda.getByLabel('Next status').selectOption('UnderReview');
    await sltda.getByLabel('Review or status-change remark').fill('Browser review completed');
    await sltda.getByRole('button', { name: 'Record status', exact: true }).click();
    await actionComplete(sltda);
    await sltda.getByRole('checkbox', { name: 'SLCG', exact: true }).check();
    await sltda.getByText('Receiving authorities: SLCG', { exact: true }).waitFor();
    await sltda.getByRole('checkbox', { name: /^Wildlife/ }).check();
    await sltda.getByLabel('Forwarding note (optional)').fill('Browser referral for safety investigation');
    await sltda.getByRole('button', { name: 'Confirm forwarding' }).click();
    await sltda.getByRole('heading', { name: 'Authority assignments' }).waitFor();
    await sltda.locator('aside').getByText('SLCG', { exact: true }).first().waitFor();
    assert.equal(await sltda.getByRole('checkbox', { name: 'SLCG', exact: true }).count(), 0);
    assert.equal(await sltda.locator('aside strong').filter({ hasText: /^SLCG$/ }).count(), 2);
    assert.equal(await sltda.locator('aside strong').filter({ hasText: /^(Admin|OPS)$/ }).count(), 0);
    await sltda.locator('aside').getByText('Wildlife', { exact: true }).waitFor();
    const ops = await session('OPS');
    await ops.goto(`${base}ops/complaint-notifications`);
    await ops.getByRole('button').filter({ hasText: new RegExp(`WWMS-${complaintId}`, 'i') }).click();
    await ops.getByRole('button', { name: 'Acknowledge receipt' }).click();
    await ops.getByLabel('Response or progress remark').waitFor();
    await assertSingleHeader(ops);
    await ops.getByLabel('Response or progress remark').fill('Browser official OPS response');
    await ops.getByRole('button', { name: 'Record authority update' }).click();
    await actionComplete(ops);
    await ops.getByLabel('Response or progress remark').fill('Browser follow-up response');
    await ops.getByRole('button', { name: 'Record authority update' }).click();
    await ops.getByText('Browser follow-up response', { exact: true }).waitFor();
    assert.equal(await ops.locator('aside').getByText('Wildlife', { exact: true }).count(), 0);
    const wildlife = await session('Wildlife');
    await wildlife.goto(`${base}wildlife/complaints/${complaintId}`);
    await wildlife.getByRole('button', { name: 'Acknowledge receipt' }).click();
    await assertSingleHeader(wildlife);
    await wildlife.getByLabel('Response or progress remark').fill('Browser official Wildlife response');
    await wildlife.getByRole('button', { name: 'Record authority update' }).click();
    await actionComplete(wildlife);
    const slcgAdmin = await session('Admin');
    await slcgAdmin.goto(`${base}admin/complaints/${complaintId}`);
    await slcgAdmin.getByRole('button', { name: 'Acknowledge receipt' }).click();
    await slcgAdmin.getByLabel('Response or progress remark').fill('SLCG official response');
    await slcgAdmin.getByRole('button', { name: 'Record authority update' }).click();
    await actionComplete(slcgAdmin);
    await sltda.reload();
    await sltda.getByLabel('Next status').selectOption('Resolved');
    await sltda.getByLabel('Review or status-change remark').fill('Browser resolution after both responses');
    await sltda.getByRole('button', { name: 'Record status', exact: true }).click();
    await actionComplete(sltda);
    await sltda.locator('section').first().getByText('Resolved', { exact: true }).waitFor();
    await sltda.getByLabel('Next status').selectOption('Closed');
    await sltda.getByRole('button', { name: 'Record status', exact: true }).click();
    await sltda.locator('section').first().getByText('Closed', { exact: true }).waitFor();
    await sltda.getByLabel('Next status').selectOption('Reopened');
    await sltda.getByLabel('Review or status-change remark').fill('Browser further action required');
    await sltda.getByRole('button', { name: 'Record status', exact: true }).click();
    await sltda.locator('ol').getByText('Reopened', { exact: true }).waitFor();
    await sltda.setViewportSize({ width: 390, height: 844 });
    await assertNoOverflow(sltda);
    if (screenshots) await sltda.screenshot({ path: path.join(screenshots, 'complaint-mobile.png'), fullPage: true });
    await sltda.getByRole('link', { name: 'Complaint updates' }).click();
    await sltda.getByRole('button', { name: 'Mark read', exact: true }).first().click();
    await sltda.getByRole('button', { name: 'Mark unread', exact: true }).waitFor();
    await sltda.reload();
    await sltda.getByRole('button', { name: 'Mark unread', exact: true }).waitFor();
    await sltda.goto(`${base}sltda/passengers/${passengerId}`);
    await sltda.getByRole('heading', { name: 'Passenger One', exact: true }).waitFor();
    await assertNoOverflow(sltda);
    await sltda.getByRole('button', { name: 'Open navigation', exact: true }).click();
    const mobileNav = sltda.getByRole('navigation', { name: 'SLTDA mobile navigation', exact: true });
    await mobileNav.getByRole('link', { name: 'Trip history', exact: true }).click();
    await sltda.getByRole('heading', { name: 'Trip history', exact: true }).waitFor();
    assert.equal(await mobileNav.count(), 0);
    await assertNoOverflow(sltda);
    await sltda.getByRole('button', { name: 'Open navigation', exact: true }).click();
    await sltda.keyboard.press('Escape');
    assert.equal(await sltda.getByRole('button', { name: 'Open navigation', exact: true }).getAttribute('aria-expanded'), 'false');
    await sltda.goto(`${base}sltda?from=2000-01-01&to=2000-01-07`);
    await sltda.getByText('No passenger registrations in this period', { exact: true }).waitFor();
    await sltda.getByText('No complaints or inquiries in this period', { exact: true }).waitFor();
    await assertNoOverflow(sltda);
    if (screenshots) await sltda.screenshot({ path: path.join(screenshots, 'sltda-mobile-empty.png'), fullPage: true });
    await sltda.setViewportSize({ width: 320, height: 740 });
    await assertNoOverflow(sltda);
    await sltda.getByText('1 Jan 2000 — 7 Jan 2000', { exact: true }).click();
    await sltda.getByLabel('Reporting period from', { exact: true }).waitFor();
    await assertNoOverflow(sltda);
    const pickerBounds = await sltda.locator('form').filter({ hasText: 'Custom reporting period' }).boundingBox();
    assert(pickerBounds && pickerBounds.x >= 0 && pickerBounds.x + pickerBounds.width <= 320, 'Date picker must stay inside the narrow viewport');
    await sltda.keyboard.press('Escape');
    await sltda.goto(`${base}sltda?from=2026-10-20&to=2026-10-18`);
    await sltda.getByRole('alert').filter({ hasText: 'Choose a valid inclusive date range' }).waitFor();
    assert.equal(await sltda.getByRole('link', { name: /^Total passengers:/ }).count(), 0, 'An API failure must not display fabricated statistics');
    const admin = await session('Admin');
    await admin.goto(`${base}admin/complaints`);
    await admin.getByRole('heading', { name: 'Complaint oversight', exact: true }).waitFor();
    await assertSingleHeader(admin);
    await admin.getByRole('link', { name: 'Passenger monitoring', exact: true }).waitFor();
    if (screenshots) await admin.screenshot({ path: path.join(screenshots, 'admin-complaints.png'), fullPage: true });
    await admin.getByRole('link', { name: 'Staff', exact: true }).click();
    await admin.getByRole('button', { name: 'Add staff', exact: true }).click();
    const staffForm = admin.locator('form').filter({ hasText: 'Create staff account' });
    await staffForm.getByLabel('Full name', { exact: true }).fill('Browser Created SLTDA Officer');
    await staffForm.getByLabel('Username', { exact: true }).fill('browser-created-sltda');
    await staffForm.getByLabel('Email', { exact: true }).fill('browser-created-sltda@staff-test.example');
    await staffForm.getByLabel('Temporary password', { exact: true }).fill('BrowserStaff#2026!Only');
    await staffForm.getByLabel('Confirm password', { exact: true }).fill('BrowserStaff#2026!Only');
    await staffForm.getByRole('combobox').selectOption('SLTDA');
    await staffForm.getByRole('button', { name: 'Create staff', exact: true }).click();
    await admin.getByRole('cell', { name: 'Browser Created SLTDA Officer', exact: true }).waitFor();
    assert.equal(await staffForm.count(), 0, 'Staff creation completes and closes the form');
    const harbour = await session('HarbourOfficer');
    await harbour.goto(`${base}harbour-officer/complaints`);
    await harbour.getByRole('heading', { name: 'Assigned complaints', exact: true }).waitFor();
    await assertSingleHeader(harbour);
    assert.equal(await harbour.locator('header').getByRole('link', { name: 'Complaints', exact: true }).count(), 1);
    const shore = await session('ShoreCrew');
    await shore.goto(`${base}ops/complaints`);
    await shore.getByRole('heading', { name: 'Access denied' }).waitFor();
    await shore.goto(`${base}sltda/passengers`);
    await shore.getByRole('heading', { name: 'Access denied' }).waitFor();
    assert.deepEqual(errors, [], 'No uncaught browser errors');
    console.log('Live browser workflow passed: passenger history, forwarding, scoped responses, follow-up, reopening, persistent notifications, mobile layouts, and route protection.');
  } catch (error) {
    if (screenshots) {
      for (const [index, context] of contexts.entries()) {
        for (const page of context.pages()) await page.screenshot({ path: path.join(screenshots, `failure-${index}.png`), fullPage: true }).catch(() => {});
      }
    }
    throw error;
  } finally { await Promise.all(contexts.map(context => context.close())); await browser.close(); }
}
main().catch(error => { console.error(error); process.exitCode = 1; });
